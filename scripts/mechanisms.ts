// The mechanism catalog, docs/mechanisms/: which kinds of mechanism the surveyed sets use, when
// each first appears and how often it's used since. Read from the kinds in data/mechanisms.json
// and the `mechanisms` each curated function lists in data/sets/<set>.json, with each set's year
// and name from models/technic-sets.csv and what Kinebrick does with each function from the
// set's `generated`. Writes docs/mechanisms/README.md, the timeline and a table of every kind,
// and a page per kind, docs/mechanisms/<kind>.md, afresh each time.
//
// Run with: npm run mechanisms (or, to write it somewhere else, npx tsx scripts/mechanisms.ts
// <folder>, as the test that it's up to date does)

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT_DIR = process.argv[2] ?? join('docs', 'mechanisms');
const SETS_DIR = join('data', 'sets');
const VIEWER = 'https://erik-larsen.github.io/kinebrick/?model=';

interface Kind {
  kind: string;
  name: string;
  family: string;
  means: string;
}

// One use of a kind: a function of a set that lists it.
interface Use {
  set: string;
  year: number;
  does: string;
  detail: string;
  main: boolean; // the function's first kind, what it's mostly about
  result: string; // from the function check: works, partly, no, skipped, not checked
}

// The fields of a CSV line. Fields may be quoted, with commas inside.
function csvFields(line: string): string[] {
  return [...line.matchAll(/("([^"]*(?:""[^"]*)*)"|[^,]*)(,|$)/g)].slice(0, -1).map((m) => (m[2] !== undefined ? m[2].replaceAll('""', '"') : m[1]));
}

const vocabulary: { families: string[]; kinds: Kind[] } = JSON.parse(readFileSync('data/mechanisms.json', 'utf-8'));
const kinds = vocabulary.kinds;

const lines = readFileSync('models/technic-sets.csv', 'utf-8').trim().split('\n');
const header = csvFields(lines[0]);
const rows = lines.slice(1).map((line) => Object.fromEntries(header.map((name, i) => [name, csvFields(line)[i] ?? ''])));
const csv = new Map(rows.map((row) => [row.set_num, row]));

// The models the viewer has, so a set built in one links to it.
const viewerModels = Object.keys(JSON.parse(readFileSync('packed/models.json', 'utf-8')));

const uses = new Map<string, Use[]>(kinds.map((k) => [k.kind, []]));
const sets: { set: string; year: number }[] = [];
let functionCount = 0;
for (const file of readdirSync(SETS_DIR).filter((f) => f.endsWith('.json'))) {
  const data = JSON.parse(readFileSync(join(SETS_DIR, file), 'utf-8'));
  const year = Number(csv.get(data.set)!.year);
  sets.push({ set: data.set, year });
  data.curated.functions.forEach((f: any, i: number) => {
    functionCount++;
    f.mechanisms.forEach((tag: string, t: number) => {
      const [kind, ...detail] = tag.split(': ');
      if (!uses.has(kind)) throw new Error(`${data.set} function ${i}: no kind ${kind} in data/mechanisms.json`);
      uses.get(kind)!.push({ set: data.set, year, does: f.does, detail: detail.join(': '), main: t === 0, result: data.generated.functions?.[i]?.result ?? 'not checked' });
    });
  });
}
for (const list of uses.values()) list.sort((a, b) => a.year - b.year || a.set.localeCompare(b.set, 'en', { numeric: true }));

const decade = (year: number) => `${Math.floor(year / 10) * 10}s`;
const decades = [...new Set(sets.map((s) => decade(s.year)))].sort();
const setsIn = (d: string) => sets.filter((s) => decade(s.year) === d).length;
const firstYear = Math.min(...sets.map((s) => s.year));
const lastYear = Math.max(...sets.map((s) => s.year));

// A set's number and name, linked to its model in the viewer, or to BrickLink.
function setLink(set: string): string {
  const row = csv.get(set)!;
  const model = viewerModels.find((m) => m.startsWith(set.replace(/-1$/, '') + '-'));
  const url = model ? VIEWER + encodeURIComponent(model) : row.bricklink_url;
  return `[${set.replace(/-1$/, '')} ${row.name}](${url})`;
}

const distinctSets = (list: Use[]) => [...new Set(list.map((u) => u.set))];

// How many functions came out each way in the function check.
function results(list: Use[]): string {
  const counts = new Map<string, number>();
  for (const u of list) counts.set(u.result, (counts.get(u.result) ?? 0) + 1);
  return ['works', 'partly', 'no', 'skipped', 'not checked', 'error'].filter((r) => counts.has(r)).map((r) => `${counts.get(r)} ${r}`).join(', ');
}

const generatedNote = 'Generated by `npm run mechanisms` (`scripts/mechanisms.ts`) from the kinds in [data/mechanisms.json](../../data/mechanisms.json) and the `mechanisms` of each function in [data/sets/](../../data/sets/README.md); don\'t edit it by hand.';

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

// The index: the timeline of first appearances, and every kind by family.
const used = kinds.filter((k) => uses.get(k.kind)!.length);
const firsts = used.map((k) => ({ k, list: uses.get(k.kind)! })).sort((a, b) => a.list[0].year - b.list[0].year || kinds.indexOf(a.k) - kinds.indexOf(b.k));
let index = `# Mechanisms\n\nThe kinds of mechanism in LEGO Technic sets: when each first appears, and how often it's used since, from the ${functionCount} functions of the ${sets.length} sets Kinebrick Viewer has surveyed so far (${firstYear} to ${lastYear}). Each function's kinds are tagged from what its building instructions show it doing. ${generatedNote}\n\n`;
index += `## Timeline\n\nEach kind by the year it first appears, the newest last.\n\n| Year | Kind | Family | First in |\n|---|---|---|---|\n`;
for (const { k, list } of firsts) {
  const first = distinctSets(list.filter((u) => u.year === list[0].year));
  index += `| ${list[0].year} | [${k.name}](${k.kind}.md) | ${k.family} | ${first.map(setLink).join(', ')} |\n`;
}
index += `\n## Kinds\n\nHow many sets use each kind, by decade (with how many sets of that decade are surveyed), and how many of its functions Kinebrick moves as it should.\n`;
for (const family of vocabulary.families) {
  const inFamily = kinds.filter((k) => k.family === family);
  index += `\n### ${family}\n\n| Kind | Sets | First | ${decades.map((d) => `${d} (${setsIn(d)})`).join(' | ')} | Kinebrick |\n|---|---|---|${decades.map(() => '---|').join('')}---|\n`;
  for (const k of inFamily) {
    const list = uses.get(k.kind)!;
    const byDecade = decades.map((d) => distinctSets(list.filter((u) => decade(u.year) === d)).length || '');
    index += `| [${k.name}](${k.kind}.md) | ${distinctSets(list).length} | ${list[0]?.year ?? ''} | ${byDecade.join(' | ')} | ${results(list)} |\n`;
  }
}
writeFileSync(join(OUT_DIR, 'README.md'), index);

// A page per kind.
for (const k of kinds) {
  const list = uses.get(k.kind)!;
  let page = `# ${k.name}\n\n${k.means} (${k.family}.)\n\n`;
  if (!list.length) {
    page += 'No surveyed set uses it yet.\n';
  } else {
    // The first year's sets, quoting the function there that's most about this kind.
    const first = list.filter((u) => u.year === list[0].year);
    const quote = first.find((u) => u.main) ?? first[0];
    page += `First appears in ${list[0].year}, in ${distinctSets(first).map(setLink).join(' and ')}: ${quote.does}\n\n`;
    page += `Used in ${distinctSets(list).length} of the ${sets.length} surveyed sets, by ${list.length} functions. Kinebrick: ${results(list)}.\n\n`;
    page += `## By decade\n\n| | ${decades.join(' | ')} |\n|---|${decades.map(() => '---|').join('')}\n`;
    page += `| Sets | ${decades.map((d) => `${distinctSets(list.filter((u) => decade(u.year) === d)).length} of ${setsIn(d)}`).join(' | ')} |\n`;
    page += `| Functions | ${decades.map((d) => list.filter((u) => decade(u.year) === d).length).join(' | ')} |\n`;
    const details = [...new Set(list.map((u) => u.detail).filter((d) => d))];
    if (details.length) {
      page += `\n## Details\n\nEach detail by the set it first appears in.\n\n| Detail | First in | Sets |\n|---|---|---|\n`;
      for (const detail of details) {
        const withIt = list.filter((u) => u.detail === detail);
        page += `| ${detail} | ${withIt[0].year}, ${setLink(withIt[0].set)} | ${distinctSets(withIt).length} |\n`;
      }
    }
    page += `\n## Sets\n`;
    for (const set of distinctSets(list)) {
      const inSet = list.filter((u) => u.set === set);
      page += `\n**${inSet[0].year}, ${setLink(set)}**\n\n`;
      for (const u of inSet) page += `- ${u.detail ? `*${u.detail}:* ` : ''}${u.does} (${u.result})\n`;
    }
  }
  page += `\n---\n\n[All mechanisms](README.md). ${generatedNote}\n`;
  writeFileSync(join(OUT_DIR, `${k.kind}.md`), page);
}

console.log(`${used.length} of ${kinds.length} kinds used, by ${functionCount} functions in ${sets.length} sets: written to ${OUT_DIR}/`);
